import { expect, test } from '@playwright/test'

test('forecast, navigation and responsive layouts',async({page})=>{
  await page.goto('/')
  await expect(page.getByText('Нажмите «Рассчитать», чтобы увидеть прогноз.')).toBeVisible()
  await page.getByRole('button',{name:'Рассчитать',exact:true}).click()
  await expect(page.getByText('816 чел.',{exact:true}).first()).toBeVisible()
  for(const width of [1440,1024,768,390]){
    await page.setViewportSize({width,height:900})
    await expect(page.getByRole('img',{name:'График квантилей спроса'})).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
  await page.getByLabel('Куда',{exact:true}).selectOption('LED')
  await page.getByLabel('Цена билета, ₽').fill('1000000')
  await expect(page.getByText('816 чел.',{exact:true}).first()).toBeVisible()
  await page.getByRole('button',{name:/Дата вылета/}).click()
  await page.getByRole('button',{name:'Следующий месяц'}).click()
  await expect(page.getByRole('button',{name:'2 июля',exact:true})).toBeDisabled()
  const calculation=page.waitForRequest(r=>r.url().endsWith('/api/forecast')&&r.postDataJSON().date==='2026-07-01')
  await page.getByRole('button',{name:/^1 июля,/}).click()
  expect((await calculation).postDataJSON()).toEqual({route:'MOW-LED',date:'2026-07-01',price:1000000})
  await expect(page.getByRole('dialog',{name:'Календарь рекомендованных цен'})).toBeHidden()
  await expect(page.getByLabel('Цена билета, ₽')).toHaveValue('1000000')
  await expect(page.getByText('0 бил.',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Pricing Lab',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Сравнение результатов'})).toBeVisible()
  await expect(page.getByRole('img',{name:'График выручки'})).toBeVisible()
})

