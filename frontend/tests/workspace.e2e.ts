test('calendar shows route prices and dismisses on mobile',async({page,request})=>{
  await page.setViewportSize({width:390,height:650})
  await page.goto('/pricing')
  const trigger=page.getByRole('button',{name:/Дата вылета/})
  const calendar=page.getByRole('dialog',{name:'Календарь рекомендованных цен'})
  await trigger.click()
  await expect(calendar.getByRole('button',{name:/^1 июня, 9\s492 ₽$/})).toBeVisible()
  const bounds=(await calendar.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x+bounds.width).toBeLessThanOrEqual(390)
  expect(bounds.y+bounds.height).toBeLessThanOrEqual(650)
  await page.keyboard.press('Escape')
  await expect(calendar).toBeHidden()
  await trigger.click()
  await page.locator('.topbar').click({position:{x:4,y:4}})
  await expect(calendar).toBeHidden()
  await page.getByLabel('Куда',{exact:true}).selectOption('LED')
  await trigger.click()
  const prices=await (await request.get('/api/calendar/prices?route=MOW-LED')).json()
  const price=prices['2026-06-01'].toLocaleString('ru-RU')
  await expect(calendar.getByRole('button',{name:'1 июня, '+price+' ₽',exact:true})).toBeVisible()
})

test('Pricing Lab shows demand at both prices for all nine quantiles', async ({page}) => {
  await page.goto('/pricing')
  await page.getByLabel('Цена билета, ₽').fill('8000')
  await page.getByRole('button', {name:'Рассчитать', exact:true}).click()

  const chart = page.getByRole('img', {name:'График квантилей спроса'})
  const areas = chart.locator('.recharts-area')
  await expect(areas).toHaveCount(2)
  // MOW-AER, 1 June. Base price 9000, sensitivity 0.141.
  const baseDemand = [698, 739, 768, 792, 816, 839, 863, 893, 933]
  const mlPrice = 9492
  const format = (value: number) => value.toLocaleString('ru-RU', {maximumFractionDigits:1})
  const blueDots = areas.nth(0).locator('.recharts-area-dot')
  const orangeDots = areas.nth(1).locator('.recharts-area-dot')
  await expect(blueDots).toHaveCount(9)
  await expect(orangeDots).toHaveCount(9)
  await expect(chart.locator('.recharts-reference-line')).toHaveCount(1)
  await expect(chart.locator('.recharts-reference-dot')).toHaveCount(1)

  for (const [index, demand] of baseDemand.entries()) {
    await orangeDots.nth(index).hover()
    const tooltip = chart.locator('.demand-tooltip')
    await expect(tooltip).toBeVisible()
    await expect(tooltip).toContainText('Квантиль ' + format((index + 1) / 10))
    await expect(tooltip).toContainText('Спрос при вашей цене · ' + format(demand + 141) + ' чел.')
    await expect(tooltip).toContainText('Рекомендованная цена ML · ' + format(mlPrice) + ' ₽')
    await expect(tooltip).toContainText('Спрос при цене ML · ' + format(demand - 0.141 * (mlPrice - 9000)) + ' чел.')
  }

  await page.getByRole('link', {name:'Главная', exact:true}).click()
  await expect(page.getByRole('img', {name:'График квантилей спроса'}).locator('.recharts-area')).toHaveCount(1)
})

test('both demand lines coincide at the median ML price', async ({page}) => {
  await page.goto('/pricing')
  await page.getByLabel('Цена билета, ₽').fill('9492')
  await page.getByRole('button', {name:'Рассчитать', exact:true}).click()

  const chart = page.getByRole('img', {name:'График квантилей спроса'})
  const areas = chart.locator('.recharts-area')
  const blueDots = areas.nth(0).locator('.recharts-area-dot')
  const orangeDots = areas.nth(1).locator('.recharts-area-dot')
  await expect(blueDots).toHaveCount(9)
  await expect(orangeDots).toHaveCount(9)
  for (let index = 0; index < 9; index++) {
    const blue = blueDots.nth(index)
    const orange = orangeDots.nth(index)
    expect(await blue.getAttribute('cx')).toBe(await orange.getAttribute('cx'))
    expect(await blue.getAttribute('cy')).toBe(await orange.getAttribute('cy'))
  }
})
